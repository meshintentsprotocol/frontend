import { describe, it, expect } from 'vitest';
import { ElectrumNetworkProvider } from 'cashscript';
import vectorsFile from '../__fixtures__/poolVectors.json';
import {
  artifactHash, buildPoolContract, categoryToLE, constructorArgs, contractFromArgs, fitSafe, MAX_SAFE, parseDecimal,
  poolOutputFor, poolSide, priceFromTokenPerBch, sideParams, tokenPerBchFromParams, tokenPerBchFromSatsPerUnit,
  traderTokenPerBch, validatePoolParams, type PoolParams,
} from '../pool';
import { lockingBytecodeOf } from '../poolTx';
import { formatUnits, parseUnits, formatSatsCompact } from '../format';

const PUSD = 'dfe50223c8d5cba8dcef8dff6d92b61deb88a8ba44947367f2b746487b56039b';
const hex = (b: Uint8Array) => Array.from(b).map(x => x.toString(16).padStart(2, '0')).join('');

describe('parity with the server (vectors generated by meshserver/scripts/gen-pool-vectors.ts)', () => {
  it('uses the same covenant bytecode', () => {
    expect(artifactHash()).toBe(vectorsFile.artifactHash);
  });

  for (const network of ['chipnet', 'mainnet'] as const) {
    const provider = new ElectrumNetworkProvider(network);
    for (const v of (vectorsFile.vectors as any)[network]) {
      it(`${network} ${v.params.tokenCategoryIn.slice(0, 6)}→${v.params.tokenCategoryOut.slice(0, 6)} ${v.params.priceNum}/${v.params.priceDen} fee ${v.params.feeBps}`, () => {
        const c = buildPoolContract(v.params as PoolParams, provider);
        expect(c.address).toBe(v.address);
        expect(c.tokenAddress).toBe(v.tokenAddress);
        expect(hex(lockingBytecodeOf(c.address))).toBe(v.lockingBytecode);
        expect(constructorArgs(v.params as PoolParams)).toEqual(v.constructorArgs);
        // server-provided args rebuild the same contract, and a mismatch is refused
        expect(contractFromArgs(v.constructorArgs, v.address, provider).address).toBe(v.address);
        expect(() => contractFromArgs(v.constructorArgs, 'bchtest:pwrong', provider)).toThrow(/do not match/);
      });
    }
  }
});

describe('params', () => {
  const base: PoolParams = { ownerPkh: 'ab'.repeat(20), tokenCategoryIn: PUSD, tokenCategoryOut: '0x', priceNum: 2000, priceDen: 1, feeBps: 30 };
  it('validates like the server', () => {
    expect(validatePoolParams(base)).toBeNull();
    expect(validatePoolParams({ ...base, tokenCategoryOut: PUSD })).toMatch(/exactly one/);
    expect(validatePoolParams({ ...base, tokenCategoryIn: '0x' })).toMatch(/exactly one/);
    expect(validatePoolParams({ ...base, priceNum: 1.5 })).toMatch(/priceNum/);
    expect(validatePoolParams({ ...base, feeBps: 10_000 })).toMatch(/feeBps/);
    expect(validatePoolParams({ ...base, ownerPkh: 'zz' })).toMatch(/ownerPkh/);
  });
  it('encodes categories little-endian, BCH as 0x', () => {
    expect(categoryToLE(PUSD)).toBe('0x' + PUSD.match(/.{2}/g)!.reverse().join(''));
    expect(categoryToLE('BCH')).toBe('0x');
    expect(categoryToLE('0x')).toBe('0x');
  });
  it('sideParams sets direction', () => {
    const p = sideParams('SELL_TOKEN', PUSD, 'AB'.repeat(20), { num: 1n, den: 2100n }, 30);
    expect(p).toMatchObject({ tokenCategoryIn: '0x', tokenCategoryOut: PUSD, ownerPkh: 'ab'.repeat(20) });
    expect(poolSide(p)).toBe('SELL_TOKEN');
  });
});

describe('pricing', () => {
  it('parses decimals exactly', () => {
    expect(parseDecimal('311.25')).toEqual({ num: 31125n, den: 100n });
    expect(() => parseDecimal('0')).toThrow();
    expect(() => parseDecimal('1e5')).toThrow();
  });

  it('SELL_BCH: sats per token unit = 1e8 / (P · 10^dec)', () => {
    const f = priceFromTokenPerBch('311.25', 2, 'SELL_BCH');
    // 1e8 · 100 / (31125 · 100) = 1e8 / 31125 → reduced
    expect(Number(f.num) / Number(f.den)).toBeCloseTo(1e8 / 31125, 9);
    const p = sideParams('SELL_BCH', PUSD, 'ab'.repeat(20), f, 30);
    expect(tokenPerBchFromParams(p, 2)).toBeCloseTo(311.25, 9);
    // trader selling tokens pays more tokens per BCH than the LP's quote
    expect(traderTokenPerBch(p, 2)).toBeCloseTo(311.25 / 0.997, 6);
  });

  it('SELL_TOKEN: token units per sat = P · 10^dec / 1e8', () => {
    const f = priceFromTokenPerBch('311.25', 2, 'SELL_TOKEN');
    expect(Number(f.num) / Number(f.den)).toBeCloseTo(31125 / 1e8, 12);
    const p = sideParams('SELL_TOKEN', PUSD, 'ab'.repeat(20), f, 30);
    expect(tokenPerBchFromParams(p, 2)).toBeCloseTo(311.25, 9);
    expect(traderTokenPerBch(p, 2)).toBeCloseTo(311.25 * 0.997, 6);
  });

  it('keeps num/den within safe integers, rounding the price down', () => {
    const f = fitSafe({ num: 10n ** 30n + 7n, den: 3n * 10n ** 20n + 1n });
    expect(f.num <= MAX_SAFE && f.den <= MAX_SAFE).toBe(true);
    expect(Number(f.num) / Number(f.den)).toBeLessThanOrEqual((1e30 + 7) / (3e20 + 1));
    const g = priceFromTokenPerBch('123456.123456789123', 8, 'SELL_TOKEN');
    expect(g.num <= MAX_SAFE && g.den <= MAX_SAFE).toBe(true);
  });

  it('pool output equals the covenant formula', () => {
    const p: PoolParams = { ownerPkh: 'ab'.repeat(20), tokenCategoryIn: PUSD, tokenCategoryOut: '0x', priceNum: 2000, priceDen: 1, feeBps: 30 };
    expect(poolOutputFor(p, 10n)).toBe(19_940n);
    const q: PoolParams = { ...p, tokenCategoryIn: '0x', tokenCategoryOut: PUSD, priceNum: 1, priceDen: 2100 };
    expect(poolOutputFor(q, 20_000n)).toBe(9n);
  });

  it('converts the server market reference', () => {
    // 320,303 sats per 0.01 pUSD unit ⇒ ~312.2 pUSD per BCH
    expect(tokenPerBchFromSatsPerUnit('320303', 2)).toBeCloseTo(1e8 / 32030300, 6);
  });
});

describe('format', () => {
  it('parses and formats units', () => {
    expect(parseUnits('0.015', 8)).toBe(1_500_000n);
    expect(parseUnits('12', 2)).toBe(1200n);
    expect(() => parseUnits('0.001', 2)).toThrow();
    expect(formatUnits(1_500_000n, 8)).toBe('0.015');
    expect(formatUnits(123456789n, 2)).toBe('1,234,567.89');
    expect(formatSatsCompact(12_345n)).toBe('12,345 sats');
    expect(formatSatsCompact(250_000_000n)).toBe('2.5 BCH');
  });
});
